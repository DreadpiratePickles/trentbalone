/**
 * lib/generation/image-router.ts
 *
 * Multi-provider image generation with R2 storage, fallback chain,
 * budget enforcement, visual context injection, and ledger integration.
 *
 * Key invariants:
 *  - R2 provisioning checked FIRST — never generate if we cannot store the asset.
 *  - selectModel() gates on budget before any provider API call.
 *  - Generated images always stored in company R2 bucket — provider URLs never returned.
 *  - Providers return Buffer directly — no provider URL escapes this module.
 *  - Fingerprint computed from inputs only — image bytes do not affect it.
 *  - Every successful generation writes a "media" ledger entry.
 *  - R2 upload failure after generation throws ImageUploadError (no ledger entry written).
 */

import { createHash } from "node:crypto";
import OpenAI from "openai";
import { selectModel, getEstimatedCost } from "@/lib/generation/cost-optimizer";
import type { QualityTier } from "@/lib/generation/cost-optimizer";
import { checkModeration, ModerationBlockedError } from "@/lib/generation/moderation-filter";
import { getStatus } from "@/lib/provisioning/r2-provisioner";
import type { R2ProvisionedResource } from "@/lib/provisioning/r2-provisioner";
import { store } from "@/lib/store";

// ── Provider interface ────────────────────────────────────────────────────────

export interface ImageProvider {
  readonly provider: string;
  readonly model: string;
  generate(req: ImageProviderRequest): Promise<ImageProviderResponse>;
}

export type ImageProviderRequest = {
  prompt: string;
  negativePrompt?: string;
  width: number;
  height: number;
};

export type ImageProviderResponse = {
  /** Raw image bytes. Real providers download from temporary URL before returning. */
  imageData: Buffer;
  format: "png" | "jpeg" | "webp";
};

// ── R2 storage interface ──────────────────────────────────────────────────────

export interface R2StorageClient {
  upload(input: {
    bucketName: string;
    key: string;
    data: Buffer;
    contentType: string;
  }): Promise<{ url: string }>;
}

// ── Public types ──────────────────────────────────────────────────────────────

export type ImageGenerationRequest = {
  companyId: string;
  qualityTier: QualityTier;
  prompt: string;
  negativePrompt?: string;
  /** Injected by visual-memory.ts (Phase 4 build item 6). Appended to prompt. */
  visualContext?: { positivePrompt?: string; negativePrompt?: string };
  width?: number;
  height?: number;
  description: string;
};

export type ImageGenerationResult = {
  /** Permanent CDN URL in the company's R2 bucket. */
  r2Url: string;
  provider: string;
  model: string;
  qualityTier: QualityTier;
  /** Always a positive integer (per-image pricing). */
  actualCostCents: number;
  /** SHA-256 of generation inputs. For fingerprint-cache.ts lookup (build item 7). */
  fingerprint: string;
  format: "png" | "jpeg" | "webp";
};

export type ImageRouterOptions = {
  providers?: ImageProvider[];
  r2Client?: R2StorageClient;
  /**
   * Override R2 provisioned resource lookup.
   * - `undefined` (not provided): calls getStatus(companyId) from r2-provisioner
   * - explicit value (including `null`): uses that value directly (for testing)
   */
  r2ProvisionedResource?: R2ProvisionedResource | null;
};

// ── Error types ───────────────────────────────────────────────────────────────

export class AllProvidersFailedError extends Error {
  constructor(
    readonly qualityTier: QualityTier,
    readonly attempts: Array<{ provider: string; model: string; error: string }>
  ) {
    const summary = attempts.map(a => `${a.provider}/${a.model}: ${a.error}`).join("; ");
    super(`All image providers failed for ${qualityTier} quality. Attempts: [${summary}]`);
    this.name = "AllProvidersFailedError";
  }
}

export class R2NotProvisionedError extends Error {
  constructor(readonly companyId: string) {
    super(
      `Company ${companyId} has no R2 bucket provisioned. ` +
      `Run /provision-company to set up storage before generating images.`
    );
    this.name = "R2NotProvisionedError";
  }
}

export class ImageUploadError extends Error {
  constructor(
    readonly provider: string,
    readonly model: string,
    cause: string
  ) {
    super(`Image generated by ${provider}/${model} but R2 upload failed: ${cause}`);
    this.name = "ImageUploadError";
  }
}

