export function starterUiTemplateFiles(): Record<string, string> {
  const files: Record<string, string> = {};
  for (const name of STARTER_UI_COMPONENTS) {
    files[`src/components/ui/${name}.tsx`] = UI_FILES[name];
  }
  files["src/components/ui/index.ts"] = starterUiIndex();
  return files;
}

function starterUiIndex(): string {
  const lines = [
    "/** Available shadcn/ui primitives — import from @/components/ui/<name> */",
    ...STARTER_UI_COMPONENTS.map((name) => `export * from "./${name}"`),
  ];
  return lines.join("\n");
}
